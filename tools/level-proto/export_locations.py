#!/usr/bin/env python3
"""Writes the graph-level template libraries of the Forest and the Frost
(assets/data/room_templates_forest.json, room_templates_frost.json) from the
Swamp library, so every location plays as one big branching level that goes
underground (design/gdd/level-structure.md §3.9). The room shapes are shared;
what is swamp-only changes:

  ~ (bog water)          -> . in both (a dip in the floor stays a dip)
  B (Болотница's hummock) -> = (a plain one-way platform)

Run after export_swamp.py: python3 tools/level-proto/export_locations.py <repo_root>
"""
import json
import os
import sys

SUBS = {"forest": {"~": ".", "B": "="}, "frost": {"~": ".", "B": "="}}
PREFIX = {"forest": "fo", "frost": "fr"}


def main(root: str) -> None:
    src = json.load(open(os.path.join(root, "assets/data/room_templates_swamp.json"), encoding="utf-8"))
    for lib, subs in SUBS.items():
        out = dict(src)
        out["_note"] = ("Generated by tools/level-proto/export_locations.py from room_templates_swamp.json: "
                        "same rooms, no bog water (~ -> .) and plain platforms for hummocks (B -> =).")
        tpls = []
        for t in src["templates"]:
            t2 = dict(t)
            t2["id"] = PREFIX[lib] + t["id"][2:] if t["id"].startswith("sw") else PREFIX[lib] + "_" + t["id"]
            t2["grid"] = ["".join(subs.get(ch, ch) for ch in row) for row in t["grid"]]
            tpls.append(t2)
        out["templates"] = tpls
        path = os.path.join(root, "assets/data/room_templates_%s.json" % lib)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=1)
            f.write("\n")
        print("wrote", path, len(tpls), "templates")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
